const { expect } = require('chai')
const sinon = require('sinon')
const axios = require('axios')
const Logger = require('../../../server/Logger')
const OpenLibrary = require('../../../server/providers/OpenLibrary')
const FantLab = require('../../../server/providers/FantLab')
const MusicBrainz = require('../../../server/providers/MusicBrainz')

describe('catalog providers compatibility', () => {
  let get
  beforeEach(() => {
    get = sinon.stub(axios, 'get')
    sinon.stub(Logger, 'error')
    sinon.stub(Logger, 'debug')
    sinon.stub(console, 'error')
  })
  afterEach(() => sinon.restore())
  it('keeps OpenLibrary double slash URL, error codes and raw ISBN payload', async () => {
    const api = new OpenLibrary()
    get.resolves({ data: { title: 'Raw', extra: true } })
    expect(await api.isbnLookup('123')).to.deep.equal({ title: 'Raw', extra: true })
    expect(get.firstCall.args[0]).to.equal('https://openlibrary.org//isbn/123')
    get.rejects(new Error('offline'))
    expect(await api.isbnLookup('123')).to.deep.equal({ errorCode: 404 })
    expect(await api.searchTitle('A & B')).to.deep.equal({ errorCode: 404 })
    expect(await api.getWorksData('/works/1')).to.deep.equal({ errorCode: 500, errorMsg: 'Works Data Request failed' })
  })
  it('preserves work cover filtering, year precedence and description forms', async () => {
    const api = new OpenLibrary()
    get.onFirstCall().resolves({ data: { docs: [{ key: '/works/1', title: 'Book', author_name: ['A', 'B'], first_publish_year: 1999, cover_edition_key: 'e' }] } })
    get.onSecondCall().resolves({ data: { covers: [-1, 0, 2], first_publish_date: '2000-01', description: { value: 'Description' } } })
    const [book] = await api.searchTitle('Book')
    expect(book).to.include({ id: '1', publishedYear: '1999', author: 'A, B', description: 'Description', cover: 'https://covers.openlibrary.org/b/OLID/e-L.jpg' })
    expect(book.covers).to.deep.equal(['https://covers.openlibrary.org/b/id/2-L.jpg'])
    expect(api.parsePublishYear({}, { first_publish_date: '2000-01' })).to.equal('2000')
  })
  it('keeps FantLab genre traversal and mutating edition preference', async () => {
    const api = new FantLab()
    get.resolves({ data: { image: '/audio.jpg' } })
    const editions = { '30': { list: [{ edition_id: 1 }, { edition_id: 2, isbn: 'isbn' }] }, '10': { list: [{ edition_id: 3 }] } }
    const book = await api.cleanBookData({ authors: [{ name: ' A ' }], work_id: 1, work_name: 'Title', image: '/fallback.jpg', editions_blocks: editions, classificatory: { genre_group: [{ genre_group_id: 1, genre: [{ label: 'Fantasy', genre: [{ label: 'Epic' }] }] }] } })
    expect(book).to.include({ author: 'A', cover: 'https://fantlab.ru/audio.jpg', isbn: 'isbn' })
    expect(book.genres).to.deep.equal(['Fantasy', 'Epic'])
    expect(editions['30'].list).to.have.length(1)
    expect(get.firstCall.args[0]).to.equal('https://api.fantlab.ru/edition/2')
  })
  it('skips excluded FantLab works and preserves failure nulls', async () => {
    const api = new FantLab()
    expect(await api.getWork({ work_id: 1, work_type_id: 7 })).to.equal(null)
    expect(get.called).to.equal(false)
    get.rejects(new Error('offline'))
    expect(await api.search('Title', '')).to.deep.equal([])
    expect(await api.getWork({ work_id: 1, work_type_id: 2 })).to.equal(null)
  })
  it('keeps MusicBrainz synchronous empty search and three axios arguments', async () => {
    const api = new MusicBrainz()
    expect(api.searchTrack({})).to.deep.equal([])
    get.resolves({ data: { recordings: [{ id: 'r', extra: 1 }] } })
    expect(await api.searchTrack({ title: 'Title', artist: 'A', limit: '2' })).to.deep.equal([{ id: 'r', extra: 1 }])
    expect(get.firstCall.args).to.have.length(3)
    expect(get.firstCall.args[1].params).to.deep.equal({ query: 'artist:A AND recording:Title', limit: 2, fmt: 'json' })
    get.rejects(new Error('offline'))
    expect(await api.searchTrack({ title: 'Title' })).to.deep.equal([])
  })
})
