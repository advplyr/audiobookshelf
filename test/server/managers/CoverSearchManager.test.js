const { expect } = require('chai')
const sinon = require('sinon')
const manager = require('../../../server/managers/CoverSearchManager')
const BookFinder = require('../../../server/finders/BookFinder')
const PodcastFinder = require('../../../server/finders/PodcastFinder')

describe('CoverSearchManager compatibility', () => {
  afterEach(() => { manager.cancelAllSearches(); sinon.restore() })
  it('keeps singleton and deduplicates provider cover formats', () => {
    expect(require('../../../server/managers/CoverSearchManager')).to.equal(manager)
    expect(manager.extractCoversFromResults(['a', { covers: ['a', 'b'], cover: 'c' }])).to.deep.equal(['a', 'b', 'c'])
    expect(manager.extractCoversFromResults(null)).to.deep.equal([])
    expect(() => manager.extractCoversFromResults([null])).to.throw(TypeError)
  })
  it('completes podcast search and removes active request', async () => {
    sinon.stub(PodcastFinder, 'findCovers').resolves(['cover'])
    const result = sinon.spy(), complete = sinon.spy(), error = sinon.spy()
    await manager.startSearch('podcast', { title: 'Title', provider: 'all', podcast: true }, result, complete, error)
    expect(result.firstCall.args).to.deep.equal([{ provider: 'itunes', covers: ['cover'], total: 1 }])
    expect(complete.calledOnce).to.equal(true)
    expect(error.called).to.equal(false)
    expect(manager.activeSearches.size).to.equal(0)
  })
  it('reports provider errors but still completes remaining searches', async () => {
    sinon.stub(BookFinder, 'search').rejects(new Error('failed'))
    const complete = sinon.spy(), error = sinon.spy()
    await manager.startSearch('book', { title: 'Title', provider: 'google', podcast: false }, sinon.spy(), complete, error)
    expect(error.firstCall.args).to.deep.equal(['google', 'failed'])
    expect(complete.calledOnce).to.equal(true)
  })
  it('ignores duplicate requests and cancellation suppresses completion', async () => {
    sinon.stub(PodcastFinder, 'findCovers').returns(new Promise(() => {}))
    const complete = sinon.spy()
    const pending = manager.startSearch('id', { title: '', provider: '', podcast: true }, sinon.spy(), complete, sinon.spy())
    await manager.startSearch('id', {}, sinon.spy(), complete, sinon.spy())
    expect(manager.cancelSearch('id')).to.equal(true)
    expect(manager.cancelSearch('missing')).to.equal(false)
    await pending
    expect(complete.called).to.equal(false)
    expect(manager.activeSearches.size).to.equal(0)
  })
  it('times out and handles already-aborted signals', async () => {
    const clock = sinon.useFakeTimers(), controller = new AbortController()
    const pending = manager.executeWithTimeout(() => new Promise(() => {}), 10, controller.signal).catch(e => e)
    await clock.tickAsync(10)
    expect((await pending).name).to.equal('TimeoutError')
    controller.abort()
    const error = await manager.executeWithTimeout(() => Promise.resolve('unused'), 10, controller.signal).catch(e => e)
    expect(error.name).to.equal('AbortError')
    expect(clock.countTimers()).to.equal(0)
  })
})
